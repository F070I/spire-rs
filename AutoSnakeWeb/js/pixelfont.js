// ============================================================
// 内置 3x5 像素字体（零系统字体依赖）
// 每个字形 5 行、每行 3 位（'1' 亮）。绘制时按 px 整数放大。
// ============================================================

const PIXEL_FONT = (function () {
  const G = {
    '0': ['111','101','101','101','111'],
    '1': ['010','110','010','010','111'],
    '2': ['111','001','111','100','111'],
    '3': ['111','001','011','001','111'],
    '4': ['101','101','111','001','001'],
    '5': ['111','100','111','001','111'],
    '6': ['111','100','111','101','111'],
    '7': ['111','001','001','010','010'],
    '8': ['111','101','111','101','111'],
    '9': ['111','101','111','001','111'],
    'A': ['010','101','111','101','101'],
    'B': ['110','101','110','101','110'],
    'C': ['011','100','100','100','011'],
    'D': ['110','101','101','101','110'],
    'E': ['111','100','111','100','111'],
    'F': ['111','100','111','100','100'],
    'G': ['011','100','101','101','011'],
    'H': ['101','101','111','101','101'],
    'I': ['111','010','010','010','111'],
    'J': ['011','001','001','101','010'],
    'K': ['101','101','110','101','101'],
    'L': ['100','100','100','100','111'],
    'M': ['101','111','111','101','101'],
    'N': ['111','101','101','101','101'],
    'O': ['111','101','101','101','111'],
    'P': ['111','101','111','100','100'],
    'Q': ['111','101','101','111','001'],
    'R': ['111','101','110','101','101'],
    'S': ['011','100','010','001','110'],
    'T': ['111','010','010','010','010'],
    'U': ['101','101','101','101','111'],
    'V': ['101','101','101','101','010'],
    'W': ['101','101','111','111','101'],
    'X': ['101','101','010','101','101'],
    'Y': ['101','101','010','010','010'],
    'Z': ['111','001','010','100','111'],
    ' ': ['000','000','000','000','000'],
    ':': ['000','010','000','010','000'],
    '-': ['000','000','111','000','000'],
    '!': ['010','010','010','000','010'],
    '.': ['000','000','000','000','010'],
    '/': ['001','001','010','100','100']
  };
  // 解析为位图：每字形 5 个整数（bit2..bit0 = 左..右）
  const out = {};
  for (const ch in G) {
    out[ch] = G[ch].map(function (row) {
      return (row[0] === '1' ? 4 : 0) | (row[1] === '1' ? 2 : 0) | (row[2] === '1' ? 1 : 0);
    });
  }
  return out;
})();

// 文本宽度：n 个字符 = n*4*px - px（3 像素宽 + 1 像素间距）
function pixelTextWidth(text, px) { return text.length * 4 * px - px; }

function drawPixelText(ctx, text, x, y, px, color) {
  ctx.fillStyle = color;
  let cx = x;
  for (let i = 0; i < text.length; i++) {
    const g = PIXEL_FONT[text[i]] || PIXEL_FONT[' '];
    for (let ry = 0; ry < 5; ry++) {
      const bits = g[ry];
      for (let rx = 0; rx < 3; rx++) {
        if ((bits >> (2 - rx)) & 1) ctx.fillRect(cx + rx * px, y + ry * px, px, px);
      }
    }
    cx += 4 * px;
  }
}
